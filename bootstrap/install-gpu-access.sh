#!/usr/bin/env bash
# Stage 3, host part (root): let pods use the GPU only through the station's shared GPU queue.
#   - host user kube-gpu (uid 2950, group gpu): the name GPU pods have in the queue
#   - nvidia-container-toolkit-base (nvidia-ctk only, no runtime hooks) to describe the GPU as CDI
#   - /etc/cdi/nvidia.yaml              device nodes and driver libraries (generated without root, see below)
#   - /etc/cdi/station-gpu-queue.yaml   the queue socket and the /opt/gpu-queue/turn wrapper
# No device plugin: Kubernetes does not schedule the GPU at all, the existing queue does (ADR-009).
# Touches no network settings, so no auto-rollback timer. Logs to the same file as stage 1.
#   install-gpu-access.sh              install
#   install-gpu-access.sh --rollback   remove all of the above
set -euo pipefail
[ "$(id -u)" = 0 ] || { echo "Run as root (sudo)"; exit 1; }
TOOLKIT_VERSION=1.20.1-1
KUBE_GPU_UID=2950
REPO=$(cd "$(dirname "$0")/.." && pwd)
LOG=/var/log/gpu-platform-install.log
WRAPPER=/usr/local/lib/gpu-platform/turn
exec > >(tee -a --output-error=warn "$LOG") 2>&1
echo "=== $(date '+%F %T') $0 ${1:-install}"

if [ "${1:-}" = "--rollback" ]; then
  rm -f /etc/containerd/conf.d/50-gpu-queue.toml
  if systemctl is-active -q containerd; then systemctl restart containerd; fi
  systemctl unmask nvidia-cdi-refresh.path nvidia-cdi-refresh.service >/dev/null 2>&1 || true
  rm -f /etc/cdi/nvidia.yaml /etc/cdi/station-gpu-queue.yaml "$WRAPPER"
  rmdir /etc/cdi /usr/local/lib/gpu-platform 2>/dev/null || true
  apt-mark unhold nvidia-container-toolkit-base 2>/dev/null || true
  DEBIAN_FRONTEND=noninteractive apt-get purge -y nvidia-container-toolkit-base 2>/dev/null || true
  rm -f /etc/apt/sources.list.d/nvidia-container-toolkit.list /etc/apt/keyrings/nvidia-container-toolkit.gpg
  if id kube-gpu >/dev/null 2>&1; then userdel kube-gpu; fi
  if getent group kube-gpu >/dev/null; then groupdel kube-gpu; fi
  echo "GPU access for pods removed."
  exit 0
fi

echo "0. Preflight"
[ -f /etc/kubernetes/admin.conf ] || { echo "Install the cluster first (stage 1)"; exit 1; }
[ -S /run/gpu/ochered.sock ] || { echo "GPU queue socket /run/gpu/ochered.sock not found"; exit 1; }
for g in gpu gpudev; do getent group "$g" >/dev/null || { echo "group $g missing"; exit 1; }; done
id vorota >/dev/null 2>&1 || { echo "user vorota missing (needed to query the GPU without root)"; exit 1; }
[ -z "$(dpkg --audit 2>&1)" ] || { echo "The package system is not clean, fix it first"; exit 1; }

echo "1. Host user kube-gpu (uid $KUBE_GPU_UID), member of the queue group gpu"
getent group kube-gpu >/dev/null || groupadd -g "$KUBE_GPU_UID" kube-gpu
id kube-gpu >/dev/null 2>&1 || useradd -r -u "$KUBE_GPU_UID" -g kube-gpu -G gpu -M -d /nonexistent -s /usr/sbin/nologin kube-gpu
[ "$(id -u kube-gpu)" = "$KUBE_GPU_UID" ] || { echo "kube-gpu exists with another uid"; exit 1; }

echo "2. nvidia-container-toolkit-base $TOOLKIT_VERSION"
install -d -m 755 /etc/apt/keyrings
curl -fsSL https://nvidia.github.io/libnvidia-container/gpgkey | gpg --dearmor --yes -o /etc/apt/keyrings/nvidia-container-toolkit.gpg
echo 'deb [signed-by=/etc/apt/keyrings/nvidia-container-toolkit.gpg] https://nvidia.github.io/libnvidia-container/stable/deb/$(ARCH) /' \
  > /etc/apt/sources.list.d/nvidia-container-toolkit.list
DEBIAN_FRONTEND=noninteractive apt-get update -qq
DEBIAN_FRONTEND=noninteractive apt-get install -y -qq --no-install-recommends "nvidia-container-toolkit-base=$TOOLKIT_VERSION"
apt-mark hold nvidia-container-toolkit-base >/dev/null

echo "3. CDI description of the GPU"
# NVML used as root resets the permissions of /dev/nvidia* and would open the card to everyone until the
# station's gpu-dostup service puts them back. Query it the way gpu-dostup does: as user vorota with the card's group.
tmp=$(mktemp -d); chown vorota "$tmp"
setpriv --reuid=vorota --regid=vorota --groups="$(getent group gpudev | cut -d: -f3)" -- \
  nvidia-ctk --quiet cdi generate --output="$tmp/nvidia.yaml"
install -d -m 755 /etc/cdi
install -m 644 "$tmp/nvidia.yaml" /etc/cdi/nvidia.yaml
rm -rf "$tmp"

echo "4. Queue wrapper and the station.local/gpu-queue CDI device"
install -D -m 755 "$REPO/gpu-queue/turn" "$WRAPPER"
{
  echo "# Generated by gpu-platform/bootstrap/install-gpu-access.sh. Requested together with nvidia.com/gpu=all."
  echo 'cdiVersion: "0.6.0"'
  echo "kind: station.local/gpu-queue"
  echo "devices:"
  echo "  - name: socket"
  echo "    containerEdits:"
  echo "      env: [GPU_SOCK=/run/gpu/ochered.sock]"
  echo "      mounts:"
  echo "        # the directory, not the socket file: the dispatcher re-creates the socket when it restarts"
  echo "        - {hostPath: /run/gpu, containerPath: /run/gpu, type: bind, options: [rbind, nosuid, nodev, noexec]}"
  echo "        - {hostPath: $WRAPPER, containerPath: /opt/gpu-queue/turn, type: bind, options: [bind, ro, nosuid, nodev]}"
} > /etc/cdi/station-gpu-queue.yaml
nvidia-ctk --quiet cdi list

echo "5. No root NVML at boot: mask nvidia-cdi-refresh (it runs nvidia-smi as root)"
systemctl disable --now nvidia-cdi-refresh.path nvidia-cdi-refresh.service >/dev/null 2>&1 || true
systemctl mask nvidia-cdi-refresh.path nvidia-cdi-refresh.service >/dev/null
rm -f /var/run/cdi/nvidia.yaml

echo "6. Runtime class gpu-queue: containerd passes cdi.k8s.io/* pod annotations to the NVIDIA runtime"
# kubelet does not hand pod annotations to containerd's own CDI injection, so a dedicated runtime
# handler copies them into the OCI spec and nvidia-container-runtime (CDI mode) injects the devices.
# Pods without runtimeClassName: gpu-queue keep using plain runc.
nvidia-ctk --quiet config --set nvidia-container-runtime.mode=cdi --in-place
install -d -m 755 /etc/containerd/conf.d
cat > /etc/containerd/conf.d/50-gpu-queue.toml <<'TOML'
# gpu-platform stage 3 (ADR-009): runtime handler for RuntimeClass gpu-queue
version = 3
[plugins.'io.containerd.cri.v1.runtime'.containerd.runtimes.gpu-queue]
  runtime_type = 'io.containerd.runc.v2'
  pod_annotations = ['cdi.k8s.io/*']
  [plugins.'io.containerd.cri.v1.runtime'.containerd.runtimes.gpu-queue.options]
    BinaryName = '/usr/bin/nvidia-container-runtime'
    SystemdCgroup = true
TOML
containerd config dump | grep -q "runtimes.gpu-queue" || { echo "containerd did not load the gpu-queue runtime"; exit 1; }
if systemctl is-active -q containerd; then systemctl restart containerd; fi   # running pods keep running (shims)

echo "7. Device permissions are still owned by the queue"
getfacl -p /dev/nvidia0 | sed 's/^/   /'
echo
echo "=== GPU access for pods installed. Test: kubectl apply -f $REPO/examples/gpu-smoke-job.yaml"
